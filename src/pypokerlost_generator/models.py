class GenerationError(RuntimeError):
    """A safe, body-content-free generator failure."""


@dataclass(frozen=True, slots=True)
class SourceDocument:
    """One parsed source used only as a diagnostic and validation boundary."""

    label: str
    title: str
    version: str
    source_sha256: str
    paths: dict[str, object]
    schemas: dict[str, object]
    security_scheme: str | None
    scopes: dict[str, str]


@dataclass(frozen=True, slots=True)
class OperationSpec:
    """A globally unique operation after body-envelope validation."""

    operation: PokerlostOperation
    source: SourceDocument
    payload_schema: dict[str, object]
    result_schema: dict[str, object]
    scopes: tuple[str, ...] | None

    @property
    def class_name(self) -> str:
        return self.operation[0].upper() + self.operation[1:]

    @property
    def module_name(self) -> str:
        return to_snake_case(self.operation)


@dataclass(frozen=True, slots=True)
class TypeSpec:
    """One reachable non-canonical flat generated type."""

    name: str
    schema: dict[str, object]
    source: SourceDocument

    @property
    def module_name(self) -> str:
        return to_snake_case(self.name)


@dataclass(frozen=True, slots=True)
class RenderedFile:
    """A complete generator-owned file relative to the SDK package root."""

    path: Path
    content: str


@dataclass(frozen=True, slots=True)
class HandwrittenMethodMetadata:
    """Static contract extracted from one concrete hand-written method."""

    operation: PokerlostOperation
    scopes: tuple[str, ...] | None
    result_annotation: str
    returning: str
    fields: dict[str, tuple[str, bool]]


def to_snake_case(value: str) -> str:
    """Convert a validated Pascal/lowerCamel name into a flat module name."""
    first = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", value)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", first).lower()
