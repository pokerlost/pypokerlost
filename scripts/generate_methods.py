class GenerationError(RuntimeError):
    """A safe, body-content-free generator failure."""


@dataclass(frozen=True, slots=True)
class SourceDocument:
    """One parsed source used only as a diagnostic and validation boundary."""

    label: str
    title: str
    version: str
    source_sha256: str
    paths: dict[str, object]
    schemas: dict[str, object]


@dataclass(frozen=True, slots=True)
class OperationSpec:
    """A globally unique operation after body-envelope validation."""

    operation: PokerlostOperation
    source: SourceDocument
    payload_schema: dict[str, object]
    result_schema: dict[str, object]
    protected: bool

    @property
    def class_name(self) -> str:
        return self.operation[0].upper() + self.operation[1:]

    @property
    def module_name(self) -> str:
        return to_snake_case(self.operation)


@dataclass(frozen=True, slots=True)
class TypeSpec:
    """One reachable non-canonical flat generated type."""

    name: str
    schema: dict[str, object]
    source: SourceDocument

    @property
    def module_name(self) -> str:
        return to_snake_case(self.name)


