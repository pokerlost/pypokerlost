def _mapping(value: object, *, location: str) -> dict[str, object]:
    if not isinstance(value, dict):
        raise GenerationError(f"{location} must be an object")
    result: dict[str, object] = {}
    for key, item in value.items():
        if type(key) is not str:
            raise GenerationError(f"{location} must use string keys")
        result[key] = item
    return result


def _sequence(value: object, *, location: str) -> list[object]:
    if not isinstance(value, list):
        raise GenerationError(f"{location} must be an array")
    return list(value)


def _string(value: object, *, location: str) -> str:
    if type(value) is not str or not value:
        raise GenerationError(f"{location} must be a non-empty string")
    return value


def _optional_mapping(
    parent: Mapping[str, object],
    name: str,
    *,
    location: str,
) -> dict[str, object]:
    value = parent.get(name)
    if value is None:
        return {}
    return _mapping(value, location=f"{location}.{name}")


def _json_object(text: str, *, location: str) -> dict[str, object]:
    try:
        decoded: object = json.loads(text)
    except (json.JSONDecodeError, UnicodeError) as error:
        raise GenerationError(f"{location} is not valid JSON") from error
    return _mapping(decoded, location=location)


def _canonical_json(value: object) -> str:
    try:
        return json.dumps(
            value,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
            allow_nan=False,
        )
    except (TypeError, ValueError, UnicodeError) as error:
        raise GenerationError("OpenAPI contains a non-JSON value") from error


_SCHEMA_ANNOTATION_KEYS = frozenset(
    {
        "$defs",
        "default",
        "deprecated",
        "description",
        "examples",
        "title",
    }
)
_ORDER_INSENSITIVE_SCHEMA_ARRAYS = frozenset(
    {
        "allOf",
        "anyOf",
        "enum",
        "oneOf",
        "required",
    }
)


def _normalize_schema_contract(value: object) -> object:
    """Remove documentation-only variance while preserving wire constraints."""
    if type(value) is float and math.isfinite(value) and value.is_integer():
        return int(value)
    if isinstance(value, list):
        return [_normalize_schema_contract(item) for item in value]
    if not isinstance(value, dict):
        return value
    normalized: dict[str, object] = {}
    for raw_key, child in value.items():
        if type(raw_key) is not str:
            raise GenerationError("JSON Schema contract must use string keys")
        if raw_key in _SCHEMA_ANNOTATION_KEYS:
            continue
        normalized_child = _normalize_schema_contract(child)
        if raw_key in _ORDER_INSENSITIVE_SCHEMA_ARRAYS:
            if not isinstance(normalized_child, list):
                raise GenerationError(f"JSON Schema {raw_key} must be an array")
            normalized_child = sorted(normalized_child, key=_canonical_json)
        normalized[raw_key] = normalized_child
    return normalized


@cache
def _sdk_canonical_schema_contract(name: str) -> str:
    """Return the normalized SDK-owned contract for one canonical wire type."""
    schema_type = CANONICAL_SCHEMA_TYPES[name]
    try:
        generated: object = TypeAdapter(schema_type).json_schema(
            ref_template="#/components/schemas/{model}"
        )
    except (TypeError, ValueError) as error:
        raise GenerationError(f"SDK canonical schema {name} cannot be inspected") from error
    root = _mapping(generated, location=f"SDK canonical schema {name}")
    definitions = _optional_mapping(root, "$defs", location=f"SDK canonical schema {name}")
    without_definitions = dict(root)
    without_definitions.pop("$defs", None)
    expected_reference = f"#/components/schemas/{name}"
    if without_definitions == {"$ref": expected_reference}:
        definition = definitions.get(name)
        if definition is None:
            raise GenerationError(f"SDK canonical schema {name} has no root definition")
        without_definitions = _schema(
            definition,
            location=f"SDK canonical schema {name} definition",
        )
    return _canonical_json(_normalize_schema_contract(without_definitions))


def _reject_extensions(value: object, *, location: str) -> None:
    if isinstance(value, dict):
        for raw_key, child in value.items():
            if type(raw_key) is not str:
                raise GenerationError(f"{location} must use string keys")
            if raw_key.startswith("x-"):
                raise GenerationError(f"{location}.{raw_key} uses a forbidden vendor extension")
            _reject_extensions(child, location=f"{location}.{raw_key}")
    elif isinstance(value, list):
        for index, child in enumerate(value):
            _reject_extensions(child, location=f"{location}[{index}]")


def parse_document(raw: dict[str, object], *, label: str) -> SourceDocument:
    """Validate document-level OpenAPI invariants without service identity metadata."""
    _reject_extensions(raw, location=label)
    openapi = _string(raw.get("openapi"), location=f"{label}.openapi")
    if not openapi.startswith("3.1."):
        raise GenerationError(f"{label} must use OpenAPI 3.1.x")
    info = _mapping(raw.get("info"), location=f"{label}.info")
    title = _string(info.get("title"), location=f"{label}.info.title")
    version = _string(info.get("version"), location=f"{label}.info.version")
    if SEMVER_PATTERN.fullmatch(version) is None:
        raise GenerationError(f"{label}.info.version must be SemVer")
    paths = _mapping(raw.get("paths"), location=f"{label}.paths")
    components = _optional_mapping(raw, "components", location=label)
    schemas = _optional_mapping(components, "schemas", location=f"{label}.components")
    security_schemes = _optional_mapping(
        components,
        "securitySchemes",
        location=f"{label}.components",
    )
    if security_schemes:
        raise GenerationError(f"{label} must not publish OpenAPI security schemes")
    if _sequence(raw.get("security", []), location=f"{label}.security"):
        raise GenerationError(f"{label} must not publish document-level OpenAPI security")
    source_sha256 = hashlib.sha256(_canonical_json(raw).encode()).hexdigest()
    return SourceDocument(
        label=f"{title} ({label})",
        title=title,
        version=version,
        source_sha256=source_sha256,
        paths=paths,
        schemas=schemas,
    )


def _reference_name(reference: str, *, location: str) -> str:
    prefix = "#/components/schemas/"
    if not reference.startswith(prefix):
        raise GenerationError(f"{location} must use a local component schema reference")
    name = reference.removeprefix(prefix)
    if not name or "/" in name or "~" in name:
        raise GenerationError(f"{location} contains an invalid component reference")
    return name


def _track_canonical_references(
    value: object,
    source: SourceDocument,
    *,
    canonical_schemas: dict[str, tuple[SourceDocument, str]],
    location: str,
    seen: frozenset[str] = frozenset(),
) -> None:
    """Compare every canonical schema reachable from a business operation."""
    if isinstance(value, list):
        for index, child in enumerate(value):
            _track_canonical_references(
                child,
                source,
                canonical_schemas=canonical_schemas,
                location=f"{location}[{index}]",
                seen=seen,
            )
        return
    if not isinstance(value, dict):
        return
    reference_value = value.get("$ref")
    if reference_value is not None:
        reference = _reference_name(
            _string(reference_value, location=f"{location}.$ref"),
            location=f"{location}.$ref",
        )
        component = source.schemas.get(reference)
        if component is None:
            raise GenerationError(f"{location} references unknown schema {reference!r}")
        component_schema = _schema(
            component,
            location=f"{source.label}.components.schemas.{reference}",
        )
        if reference in CANONICAL_TYPES:
            serialized = _canonical_json(_normalize_schema_contract(component_schema))
            if serialized != _sdk_canonical_schema_contract(reference):
                raise GenerationError(
                    f"canonical schema {reference} does not match the SDK-owned contract"
                )
            previous = canonical_schemas.get(reference)
            if previous is not None and previous[1] != serialized:
                raise GenerationError(
                    f"global canonical schema collision for {reference}: "
                    f"{previous[0].label} and {source.label}"
                )
            canonical_schemas.setdefault(reference, (source, serialized))
        if reference in seen:
            return
        _track_canonical_references(
            component_schema,
            source,
            canonical_schemas=canonical_schemas,
            location=f"{source.label}.components.schemas.{reference}",
            seen=seen | {reference},
        )
        return
    for key, child in value.items():
        _track_canonical_references(
            child,
            source,
            canonical_schemas=canonical_schemas,
            location=f"{location}.{key}",
            seen=seen,
        )


def _schema(value: object, *, location: str) -> dict[str, object]:
    return _mapping(value, location=location)


def _resolve_schema(
    schema: dict[str, object],
    source: SourceDocument,
    *,
    location: str,
    seen: frozenset[str] = frozenset(),
) -> dict[str, object]:
    reference = schema.get("$ref")
    if reference is not None:
        reference_value = _string(reference, location=f"{location}.$ref")
        name = _reference_name(reference_value, location=f"{location}.$ref")
        if name in seen:
            raise GenerationError(f"{location} contains a recursive envelope schema")
        component = source.schemas.get(name)
        if component is None:
            raise GenerationError(f"{location} references unknown schema {name!r}")
        return _resolve_schema(
            _schema(component, location=f"{source.label}.components.schemas.{name}"),
            source,
            location=f"{source.label}.components.schemas.{name}",
            seen=seen | {name},
        )
    all_of = schema.get("allOf")
    if all_of is None:
        return schema
    branches = _sequence(all_of, location=f"{location}.allOf")
    merged_properties: dict[str, object] = {}
    merged_required: list[object] = []
    for index, branch in enumerate(branches):
        resolved = _resolve_schema(
            _schema(branch, location=f"{location}.allOf[{index}]"),
            source,
            location=f"{location}.allOf[{index}]",
            seen=seen,
        )
        properties = _optional_mapping(resolved, "properties", location=location)
        duplicate = sorted(set(merged_properties).intersection(properties))
        if duplicate:
            raise GenerationError(f"{location}.allOf repeats object fields: {', '.join(duplicate)}")
        merged_properties.update(properties)
        required = resolved.get("required", [])
        merged_required.extend(_sequence(required, location=f"{location}.required"))
    return {
        "type": "object",
        "properties": merged_properties,
        "required": merged_required,
        "additionalProperties": False,
    }


def _object_properties(
    schema: dict[str, object],
    source: SourceDocument,
    *,
    location: str,
) -> tuple[dict[str, object], frozenset[str]]:
    resolved = _resolve_schema(schema, source, location=location)
    properties = _optional_mapping(resolved, "properties", location=location)
    required_values = _sequence(resolved.get("required", []), location=f"{location}.required")
    required: set[str] = set()
    for item in required_values:
        required.add(_string(item, location=f"{location}.required[]"))
    if set(required) - set(properties):
        raise GenerationError(f"{location} requires unknown object fields")
    if resolved.get("additionalProperties") is not False:
        raise GenerationError(f"{location} must forbid undeclared object fields")
    return properties, frozenset(required)


def _request_envelope(
    operation: PokerlostOperation,
    raw_operation: dict[str, object],
    source: SourceDocument,
) -> tuple[dict[str, object], bool]:
    body = _mapping(raw_operation.get("requestBody"), location=f"{operation}.requestBody")
    if body.get("required") is not True:
        raise GenerationError(f"{operation} requestBody must be required")
    content = _mapping(body.get("content"), location=f"{operation}.requestBody.content")
    if set(content) != {"application/json"}:
        raise GenerationError(f"{operation} must accept exactly application/json")
    media = _mapping(content["application/json"], location=f"{operation}.requestBody.content")
    envelope_schema = _schema(media.get("schema"), location=f"{operation}.requestBody.schema")
    properties, required = _object_properties(
        envelope_schema,
        source,
        location=f"{operation}.requestBody.schema",
    )
    fields = frozenset(properties)
    if fields == {"payload"} and required == {"payload"}:
        return _schema(properties["payload"], location=f"{operation}.payload"), False
    if fields == {"authorization", "payload"} and required == fields:
        authorization = _schema(
            properties["authorization"],
            location=f"{operation}.authorization",
        )
        auth_properties, auth_required = _object_properties(
            authorization,
            source,
            location=f"{operation}.authorization",
        )
        if frozenset(auth_properties) != {"access_token"} or auth_required != {"access_token"}:
            raise GenerationError(
                f"{operation} authorization must contain only required access_token"
            )
        access_token_schema = _resolve_schema(
            _schema(auth_properties["access_token"], location=f"{operation}.access_token"),
            source,
            location=f"{operation}.access_token",
        )
        if _schema_kinds(access_token_schema) != {"string"}:
            raise GenerationError(f"{operation} authorization access_token must be a string")
        return _schema(properties["payload"], location=f"{operation}.payload"), True
    raise GenerationError(
        f"{operation} request must use PokerlostRequest or PokerlostAuthorizedRequest"
    )


def _schema_kinds(schema: dict[str, object]) -> frozenset[str]:
    raw_type = schema.get("type")
    if type(raw_type) is str:
        return frozenset({raw_type})
    if isinstance(raw_type, list):
        kinds: set[str] = set()
        for value in raw_type:
            kinds.add(_string(value, location="schema.type[]"))
        return frozenset(kinds)
    branches = schema.get("anyOf", schema.get("oneOf"))
    if branches is not None:
        branch_kinds: set[str] = set()
        for branch in _sequence(branches, location="schema union"):
            branch_kinds.update(_schema_kinds(_schema(branch, location="schema union branch")))
        return frozenset(branch_kinds)
    if "$ref" in schema:
        return frozenset({"reference"})
    if "properties" in schema:
        return frozenset({"object"})
    return frozenset()


def _strip_null(schema: dict[str, object]) -> dict[str, object]:
    branches_value = schema.get("anyOf", schema.get("oneOf"))
    if branches_value is None:
        if schema.get("type") == "null":
            return {"type": "null"}
        raw_type = schema.get("type")
        if isinstance(raw_type, list):
            remaining = [value for value in raw_type if value != "null"]
            if len(remaining) == 1:
                result = dict(schema)
                result["type"] = remaining[0]
                return result
        return schema
    remaining_branches: list[object] = []
    for branch in _sequence(branches_value, location="response.result union"):
        branch_schema = _schema(branch, location="response.result union branch")
        if _schema_kinds(branch_schema) != {"null"}:
            remaining_branches.append(branch_schema)
    if not remaining_branches:
        return {"type": "null"}
    if len(remaining_branches) == 1:
        return _schema(remaining_branches[0], location="response.result")
    return {"anyOf": remaining_branches}


def _response_result(
    operation: PokerlostOperation,
    raw_operation: dict[str, object],
    source: SourceDocument,
) -> dict[str, object]:
    responses = _mapping(raw_operation.get("responses"), location=f"{operation}.responses")
    if not responses:
        raise GenerationError(f"{operation} must document PokerlostResponse bodies")
    success_schemas: list[dict[str, object]] = []
    for status, raw_response in sorted(responses.items()):
        response = _mapping(raw_response, location=f"{operation}.responses.{status}")
        response_headers = _optional_mapping(
            response,
            "headers",
            location=f"{operation}.responses.{status}",
        )
        if response_headers:
            raise GenerationError(f"{operation} response {status} must not declare headers")
        content = _mapping(
            response.get("content"), location=f"{operation}.responses.{status}.content"
        )
        if set(content) != {"application/json"}:
            raise GenerationError(f"{operation} response {status} must contain exactly JSON")
        media = _mapping(content["application/json"], location=f"{operation}.responses.{status}")
        envelope = _resolve_schema(
            _schema(media.get("schema"), location=f"{operation}.responses.{status}.schema"),
            source,
            location=f"{operation}.responses.{status}.schema",
        )
        properties, required = _object_properties(
            envelope,
            source,
            location=f"{operation}.responses.{status}.schema",
        )
        if frozenset(properties) != ENVELOPE_FIELDS:
            raise GenerationError(f"{operation} response {status} must be PokerlostResponse")
        if required != {"ok"}:
            raise GenerationError(f"{operation} response {status} must require exactly ok")
        if _schema_kinds(
            _schema(properties["ok"], location=f"{operation}.responses.{status}.ok")
        ) != {"boolean"}:
            raise GenerationError(f"{operation} response {status} ok field must be boolean")
        for field_name in ("error", "error_message"):
            error_kinds = _schema_kinds(
                _schema(
                    properties[field_name],
                    location=f"{operation}.responses.{status}.{field_name}",
                )
            )
            if not error_kinds or not error_kinds.issubset({"string", "null"}):
                raise GenerationError(
                    f"{operation} response {status} {field_name} must be a string or null"
                )
        retry_kinds = _schema_kinds(
            _schema(
                properties["retry_after"],
                location=f"{operation}.responses.{status}.retry_after",
            )
        )
        if not retry_kinds or not retry_kinds.issubset({"integer", "number", "null"}):
            raise GenerationError(
                f"{operation} response {status} retry_after must be numeric or null"
            )
        result_schema = _schema(
            properties["result"],
            location=f"{operation}.responses.{status}.result",
        )
        if status.isdigit() and 200 <= int(status) < 300:
            success_schemas.append(envelope)
        elif _schema_kinds(result_schema) != {"null"}:
            raise GenerationError(f"{operation} failure response {status} result must be null")
    if not success_schemas:
        raise GenerationError(f"{operation} must define a JSON 2xx response")
    if len({_canonical_json(schema) for schema in success_schemas}) != 1:
        raise GenerationError(f"{operation} has incompatible 2xx response schemas")
    properties, _ = _object_properties(
        success_schemas[0],
        source,
        location=f"{operation}.response",
    )
    return _strip_null(_schema(properties["result"], location=f"{operation}.response.result"))


def collect_operations(documents: Sequence[SourceDocument]) -> tuple[OperationSpec, ...]:
    """Validate all routes and return operations only after global uniqueness holds."""
    operations: list[OperationSpec] = []
    seen: dict[PokerlostOperation, str] = {}
    seen_classes: dict[str, PokerlostOperation] = {}
    seen_modules: dict[str, PokerlostOperation] = {}
    canonical_schemas: dict[str, tuple[SourceDocument, str]] = {}
    for source in documents:
        for path, raw_path_item in sorted(source.paths.items()):
            path_item = _mapping(raw_path_item, location=f"{source.label}.paths.{path}")
            for method_name in (
                "get",
                "post",
                "put",
                "patch",
                "delete",
                "options",
                "head",
                "trace",
            ):
                raw_operation_value = path_item.get(method_name)
                if raw_operation_value is None:
                    continue
                raw_operation = _mapping(
                    raw_operation_value,
                    location=f"{source.label}.paths.{path}.{method_name}",
                )
                operation_value = _string(
                    raw_operation.get("operationId"),
                    location=f"{source.label}.paths.{path}.{method_name}.operationId",
                )
                try:
                    operation = PokerlostOperation(operation_value)
                except (TypeError, ValueError) as error:
                    raise GenerationError(
                        f"{method_name.upper()} {path} operationId must be single lowerCamelCase"
                    ) from error
                path_parameters = path_item.get("parameters", [])
                operation_parameters = raw_operation.get("parameters", [])
                if method_name == "get" and operation in INFRASTRUCTURE_GET_OPERATIONS:
                    expected_path = "/" if operation == "getRoot" else f"/{operation}"
                    if path != expected_path:
                        raise GenerationError(
                            f"infrastructure path for {operation} must equal {expected_path}"
                        )
                    if _sequence(path_parameters, location=f"{path}.parameters") or _sequence(
                        operation_parameters,
                        location=f"{operation}.parameters",
                    ):
                        raise GenerationError(
                            f"infrastructure operation {operation} must not use parameters"
                        )
                    if raw_operation.get("requestBody") is not None:
                        raise GenerationError(
                            f"infrastructure operation {operation} must not use a request body"
                        )
                    security = raw_operation.get("security", [])
                    if _sequence(security, location=f"{operation}.security"):
                        raise GenerationError(
                            f"infrastructure operation {operation} must be public"
                        )
                    continue
                if method_name != "post":
                    raise GenerationError(f"business operation {operation} must use POST")
                if path != f"/{operation}":
                    raise GenerationError(f"business path must equal /{operation}")
                if _sequence(path_parameters, location=f"{path}.parameters") or _sequence(
                    operation_parameters,
                    location=f"{operation}.parameters",
                ):
                    raise GenerationError(f"{operation} must not use OpenAPI parameters")
                security = raw_operation.get("security", [])
                if _sequence(security, location=f"{operation}.security"):
                    raise GenerationError(
                        f"{operation} must not publish an OpenAPI security scheme"
                    )
                previous = seen.get(operation)
                if previous is not None:
                    raise GenerationError(
                        f"global operation collision for {operation}: {previous} and {source.label}"
                    )
                seen[operation] = source.label
                class_name = operation[0].upper() + operation[1:]
                module_name = to_snake_case(operation)
                previous_class = seen_classes.get(class_name)
                previous_module = seen_modules.get(module_name)
                if previous_class is not None:
                    raise GenerationError(
                        f"global method class collision for {previous_class} and {operation}"
                    )
                if previous_module is not None:
                    raise GenerationError(
                        f"global method module collision for {previous_module} and {operation}"
                    )
                seen_classes[class_name] = operation
                seen_modules[module_name] = operation
                _track_canonical_references(
                    raw_operation,
                    source,
                    canonical_schemas=canonical_schemas,
                    location=f"{source.label}.paths.{path}.{method_name}",
                )
                payload_schema, protected = _request_envelope(operation, raw_operation, source)
                result_schema = _response_result(operation, raw_operation, source)
                operations.append(
                    OperationSpec(
                        operation=operation,
                        source=source,
                        payload_schema=payload_schema,
                        result_schema=result_schema,
                        protected=protected,
                    )
                )
    return tuple(sorted(operations, key=lambda item: item.operation))


def _direct_reference(schema: dict[str, object]) -> str | None:
    reference = schema.get("$ref")
    if type(reference) is str:
        return _reference_name(reference, location="schema.$ref")
    return None


def _collect_refs(
    schema: dict[str, object],
    source: SourceDocument,
    *,
    collected: set[str],
    canonical_schemas: dict[str, tuple[SourceDocument, str]],
    seen: frozenset[str] = frozenset(),
) -> None:
    reference = _direct_reference(schema)
    if reference is not None:
        if reference in collected:
            return
        component = source.schemas.get(reference)
        if component is None:
            raise GenerationError(f"unknown schema reference {reference!r}")
        component_schema = _schema(
            component,
            location=f"{source.label}.components.schemas.{reference}",
        )
        if reference in CANONICAL_TYPES:
            serialized = _canonical_json(_normalize_schema_contract(component_schema))
            if serialized != _sdk_canonical_schema_contract(reference):
                raise GenerationError(
                    f"canonical schema {reference} does not match the SDK-owned contract"
                )
            previous = canonical_schemas.get(reference)
            if previous is not None and previous[1] != serialized:
                raise GenerationError(
                    f"global canonical schema collision for {reference}: "
                    f"{previous[0].label} and {source.label}"
                )
            canonical_schemas.setdefault(reference, (source, serialized))
            if reference in seen:
                return
            _collect_refs(
                component_schema,
                source,
                collected=collected,
                canonical_schemas=canonical_schemas,
                seen=seen | {reference},
            )
            return
        collected.add(reference)
        _collect_refs(
            component_schema,
            source,
            collected=collected,
            canonical_schemas=canonical_schemas,
            seen=seen | {reference},
        )
        return
    for key in ("anyOf", "oneOf", "allOf"):
        branches = schema.get(key)
        if branches is not None:
            for branch in _sequence(branches, location=f"schema.{key}"):
                _collect_refs(
                    _schema(branch, location=f"schema.{key}[]"),
                    source,
                    collected=collected,
                    canonical_schemas=canonical_schemas,
                    seen=seen,
                )
    items = schema.get("items")
    if items is not None:
        _collect_refs(
            _schema(items, location="schema.items"),
            source,
            collected=collected,
            canonical_schemas=canonical_schemas,
            seen=seen,
        )
    properties = schema.get("properties")
    if properties is not None:
        for child in _mapping(properties, location="schema.properties").values():
            _collect_refs(
                _schema(child, location="schema property"),
                source,
                collected=collected,
                canonical_schemas=canonical_schemas,
                seen=seen,
            )


def collect_types(operations: Sequence[OperationSpec]) -> tuple[TypeSpec, ...]:
    """Collect reachable schemas and reject global class/module collisions before writing."""
    names: dict[str, SourceDocument] = {}
    modules: dict[str, str] = {}
    canonical_schemas: dict[str, tuple[SourceDocument, str]] = {}
    result: list[TypeSpec] = []
    for operation in operations:
        reachable: set[str] = set()
        _collect_refs(
            operation.payload_schema,
            operation.source,
            collected=reachable,
            canonical_schemas=canonical_schemas,
        )
        _collect_refs(
            operation.result_schema,
            operation.source,
            collected=reachable,
            canonical_schemas=canonical_schemas,
        )
        for name in sorted(reachable):
            if PYTHON_NAME_PATTERN.fullmatch(name) is None or keyword.iskeyword(name):
                raise GenerationError(f"schema {name!r} is not a valid public Python type")
            previous = names.get(name)
            if previous is not None and previous is not operation.source:
                raise GenerationError(
                    f"global schema collision for {name}: {previous.label} and "
                    f"{operation.source.label}"
                )
            module = to_snake_case(name)
            previous_name = modules.get(module)
            if previous_name is not None and previous_name != name:
                raise GenerationError(
                    f"global schema module collision for {previous_name} and {name}"
                )
            if previous is None:
                names[name] = operation.source
                modules[module] = name
                component = operation.source.schemas[name]
                result.append(
                    TypeSpec(
                        name=name,
                        schema=_schema(component, location=f"components.schemas.{name}"),
                        source=operation.source,
                    )
                )
    return tuple(sorted(result, key=lambda item: item.name))


def to_snake_case(value: str) -> str:
    """Convert a validated Pascal/lowerCamel name into a flat module name."""
    first = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", value)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", first).lower()


def _python_literal(value: object) -> str:
    if value is None or type(value) in {bool, int, float, str}:
        if type(value) is float and not math.isfinite(value):
            raise GenerationError("schema literals must be finite")
        return repr(value)
    raise GenerationError("only scalar JSON Schema literals are supported")


def _render_annotation(
    schema: dict[str, object],
    source: SourceDocument,
    *,
    imports: set[tuple[str, str]],
) -> str:
    reference = _direct_reference(schema)
    if reference is not None:
        if reference in CANONICAL_TYPES:
            imports.add(("pypokerlost.types", reference))
        else:
            imports.add((f"pypokerlost.types.{to_snake_case(reference)}", reference))
        return reference
    branches_value = schema.get("anyOf", schema.get("oneOf"))
    if branches_value is not None:
        expressions = {
            _render_annotation(
                _schema(branch, location="schema union branch"),
                source,
                imports=imports,
            )
            for branch in _sequence(branches_value, location="schema union")
        }
        return " | ".join(sorted(expressions, key=lambda item: (item == "None", item)))
    enum = schema.get("enum")
    if enum is not None:
        imports.add(("typing", "Literal"))
        values = ", ".join(
            _python_literal(value) for value in _sequence(enum, location="schema.enum")
        )
        return f"Literal[{values}]"
    raw_type = schema.get("type")
    if isinstance(raw_type, list):
        expressions = {
            _render_annotation({**schema, "type": item}, source, imports=imports)
            for item in raw_type
        }
        return " | ".join(sorted(expressions, key=lambda item: (item == "None", item)))
    if raw_type == "null":
        return "None"
    if raw_type == "boolean":
        return "bool"
    if raw_type == "integer":
        return "int"
    if raw_type == "number":
        return "float"
    if raw_type == "string":
        format_value = schema.get("format")
        if format_value == "uuid":
            imports.add(("uuid", "UUID"))
            return "UUID"
        if format_value == "date":
            imports.add(("datetime", "date"))
            return "date"
        if format_value == "date-time":
            imports.add(("datetime", "datetime"))
            return "datetime"
        if format_value == "time":
            imports.add(("datetime", "time"))
            return "time"
        if format_value is not None:
            raise GenerationError(f"unsupported string format {format_value!r}")
        return "str"
    if raw_type == "array":
        items = _schema(schema.get("items"), location="schema.items")
        return f"tuple[{_render_annotation(items, source, imports=imports)}, ...]"
    if raw_type == "object" and not schema.get("properties"):
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            value_type = _render_annotation(
                _schema(additional, location="schema.additionalProperties"),
                source,
                imports=imports,
            )
        else:
            imports.add(("pypokerlost.types", "JSONValue"))
            value_type = "JSONValue"
        return f"dict[str, {value_type}]"
    if "properties" in schema or raw_type == "object":
        raise GenerationError("inline typed object schemas must be named components")
    raise GenerationError("unsupported or untyped JSON Schema")


def _render_imports(imports: Iterable[tuple[str, str]]) -> str:
    grouped: dict[str, set[str]] = {}
    for module, name in imports:
        grouped.setdefault(module, set()).add(name)
    lines: list[str] = []
    for module in sorted(grouped):
        names = sorted(grouped[module])
        if len(names) == 1:
            lines.append(f"from {module} import {names[0]}")
        else:
            lines.append(f"from {module} import (")
            lines.extend(f"    {name}," for name in names)
            lines.append(")")
    return "\n".join(lines)


def _required_fields(
    schema: dict[str, object],
    source: SourceDocument,
    *,
    location: str,
) -> tuple[dict[str, object], frozenset[str]]:
    resolved = _resolve_schema(schema, source, location=location)
    return _object_properties(resolved, source, location=location)


def _render_field(
    name: str,
    raw_schema: object,
    *,
    required: bool,
    source: SourceDocument,
    imports: set[tuple[str, str]],
) -> str:
    if not name.isidentifier() or keyword.iskeyword(name) or name.startswith("_"):
        raise GenerationError(f"wire field {name!r} is not a supported Python identifier")
    schema = _schema(raw_schema, location=f"field {name}")
    annotation = _render_annotation(schema, source, imports=imports)
    field_kwargs: list[str] = []
    if name in SECRET_FIELD_NAMES or name.endswith(SECRET_FIELD_SUFFIXES):
        field_kwargs.append("repr=False")
    if not required:
        if "None" not in annotation.split(" | "):
            annotation = f"{annotation} | None"
        field_kwargs.insert(0, "default=None")
    if field_kwargs:
        imports.add(("pydantic", "Field"))
        return f"{name}: {annotation} = Field({', '.join(field_kwargs)})"
    return f"{name}: {annotation}"


def _generated_preamble(source: SourceDocument) -> str:
    return (
        GENERATED_HEADER
        + f"# Generator version: {GENERATOR_VERSION}\n"
        + f"# OpenAPI version: {source.version}\n"
        + f"# OpenAPI SHA256: {source.source_sha256}\n"
        + "# Do not edit manually.\n"
    )


def render_type(spec: TypeSpec) -> str:
    """Render one component into one focused flat module."""
    resolved = _resolve_schema(spec.schema, spec.source, location=spec.name)
    properties = resolved.get("properties")
    if properties is None and resolved.get("type") != "object":
        imports: set[tuple[str, str]] = set()
        annotation = _render_annotation(resolved, spec.source, imports=imports)
        return (
            _generated_preamble(spec.source)
            + f'"""Generated Pokerlost type {spec.name}."""\n\n'
            + "from __future__ import annotations\n\n"
            + (_render_imports(imports) + "\n\n" if imports else "")
            + f"type {spec.name} = {annotation}\n"
        )
    fields, required = _required_fields(
        resolved,
        spec.source,
        location=spec.name,
    )
    imports = {("pypokerlost.types.base", "PokerlostType")}
    field_lines = [
        "    "
        + _render_field(
            name,
            field,
            required=name in required,
            source=spec.source,
            imports=imports,
        )
        for name, field in sorted(fields.items())
    ]
    if not field_lines:
        field_lines = ["    pass"]
    return (
        _generated_preamble(spec.source)
        + f'"""Generated Pokerlost type {spec.name}."""\n\n'
        + "from __future__ import annotations\n\n"
        + _render_imports(imports)
        + "\n\n\n"
        + f"class {spec.name}(PokerlostType):\n"
        + "\n".join(field_lines)
        + "\n"
    )


def _method_metadata(
    path: Path, class_name: str
) -> tuple[PokerlostOperation, tuple[PokerlostScope, ...], frozenset[str], str]:
    """Read direct class metadata from a hand-written method without importing it."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    except (OSError, UnicodeError, SyntaxError) as error:
        raise GenerationError(f"cannot inspect hand-written method {path}") from error
    for node in tree.body:
        if not isinstance(node, ast.ClassDef) or node.name != class_name:
            continue
        operation: PokerlostOperation | None = None
        scopes: list[PokerlostScope] = []
        scopes_found = False
        fields: set[str] = set()
        returning: str | None = None
        for statement in node.body:
            if isinstance(statement, ast.AnnAssign) and isinstance(statement.target, ast.Name):
                fields.add(statement.target.id)
                continue
            if not isinstance(statement, ast.Assign) or len(statement.targets) != 1:
                continue
            target = statement.targets[0]
            if not isinstance(target, ast.Name):
                continue
            if target.id == "operation":
                operation = PokerlostOperation(_call_string(statement.value, "PokerlostOperation"))
            elif target.id == "required_scopes":
                scopes_found = True
                if not isinstance(statement.value, (ast.Tuple, ast.List)):
                    raise GenerationError(f"{path} required_scopes must be a literal tuple")
                scopes = [
                    PokerlostScope(_call_string(item, "PokerlostScope"))
                    for item in statement.value.elts
                ]
            elif target.id == "returning":
                if isinstance(statement.value, ast.Name):
                    returning = statement.value.id
                elif (
                    isinstance(statement.value, ast.Call)
                    and isinstance(statement.value.func, ast.Name)
                    and statement.value.func.id == "type"
                    and len(statement.value.args) == 1
                    and isinstance(statement.value.args[0], ast.Constant)
                    and statement.value.args[0].value is None
                ):
                    returning = "None"
        if operation is None or not scopes_found or returning is None:
            raise GenerationError(
                f"{path} must declare operation, required_scopes, and returning directly"
            )
        return operation, canonicalize_pokerlost_scopes(scopes), frozenset(fields), returning
    raise GenerationError(f"{path} does not define {class_name}")


def _call_string(node: ast.expr, function_name: str) -> str:
    if (
        not isinstance(node, ast.Call)
        or not isinstance(node.func, ast.Name)
        or node.func.id != function_name
        or len(node.args) != 1
        or node.keywords
        or not isinstance(node.args[0], ast.Constant)
        or type(node.args[0].value) is not str
    ):
        raise GenerationError(f"{function_name} metadata must contain one string literal")
    return node.args[0].value


def render_method(
    spec: OperationSpec,
    scopes: tuple[PokerlostScope, ...],
) -> str:
    """Render one flat method with explicit operation and scope metadata."""
    payload, required = _required_fields(
        spec.payload_schema,
        spec.source,
        location=f"{spec.operation}.payload",
    )
    imports: set[tuple[str, str]] = {
        ("pypokerlost.methods.base", "PokerlostMethod"),
        ("pypokerlost.types", "PokerlostOperation"),
    }
    result = _render_annotation(spec.result_schema, spec.source, imports=imports)
    if scopes:
        imports.add(("pypokerlost.types", "PokerlostScope"))
    field_lines = [
        "    "
        + _render_field(
            name,
            field,
            required=name in required,
            source=spec.source,
            imports=imports,
        )
        for name, field in sorted(payload.items())
    ]
    if scopes:
        scope_lines = ["    required_scopes = ("]
        scope_lines.extend(f'        PokerlostScope("{scope}"),' for scope in scopes)
        scope_lines.append("    )")
    else:
        scope_lines = ["    required_scopes = ()"]
    body = [
        f"class {spec.class_name}(PokerlostMethod[{result}]):",
        f'    operation = PokerlostOperation("{spec.operation}")',
        *scope_lines,
        f"    returning = {'type(None)' if result == 'None' else result}",
    ]
    if field_lines:
        body.extend(("", *field_lines))
    return (
        _generated_preamble(spec.source)
        + f'"""Generated Pokerlost method {spec.class_name}."""\n\n'
        + "from __future__ import annotations\n\n"
        + _render_imports(imports)
        + "\n\n\n"
        + "\n".join(body)
        + "\n"
    )


def load_scope_map(path: Path | None) -> dict[PokerlostOperation, tuple[PokerlostScope, ...]]:
    """Read the explicit checked scope input owned outside OpenAPI."""
    if path is None:
        return {}
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as error:
        raise GenerationError(f"failed to read scope map {path}") from error
    raw = _json_object(text, location=str(path))
    result: dict[PokerlostOperation, tuple[PokerlostScope, ...]] = {}
    for operation_value, scope_values in raw.items():
        try:
            operation = PokerlostOperation(operation_value)
            raw_scopes = _sequence(scope_values, location=f"{path}:{operation}")
            scopes = canonicalize_pokerlost_scopes(
                _string(value, location=f"{path}:{operation}[]") for value in raw_scopes
            )
        except (TypeError, ValueError) as error:
            raise GenerationError(f"invalid scope map entry for {operation_value}") from error
        result[operation] = scopes
    return result


def _defined_public_types(path: Path) -> tuple[str, ...]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    except (OSError, UnicodeError, SyntaxError) as error:
        raise GenerationError(f"cannot inspect public type module {path}") from error
    names: list[str] = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            names.append(node.name)
        elif isinstance(node, ast.TypeAlias) and isinstance(node.name, ast.Name):
            if not node.name.id.startswith("_"):
                names.append(node.name.id)
        elif (
            isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
            and node.name in CANONICAL_FUNCTION_EXPORTS
        ):
            names.append(node.name)
    return tuple(names)


def _defined_methods(path: Path) -> tuple[str, ...]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    except (OSError, UnicodeError, SyntaxError) as error:
        raise GenerationError(f"cannot inspect method module {path}") from error
    result: list[str] = []
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        if node.name == "PokerlostMethod" or any(
            isinstance(base, ast.Subscript)
            and isinstance(base.value, ast.Name)
            and base.value.id == "PokerlostMethod"
            for base in node.bases
        ):
            result.append(node.name)
    return tuple(result)


def _render_facade(
    *,
    title: str,
    modules: Mapping[str, tuple[str, ...]],
) -> str:
    imports = {(f".{module}", name) for module, names in modules.items() for name in names}
    exports = sorted(name for names in modules.values() for name in names)
    return (
        GENERATED_HEADER
        + f"# Generator version: {GENERATOR_VERSION}\n"
        + "# Do not edit manually.\n"
        + f'"""{title}."""\n\n'
        + "from __future__ import annotations\n\n"
        + _render_imports(imports)
        + "\n\n__all__ = (\n"
        + "".join(f'    "{name}",\n' for name in exports)
        + ")\n"
    )


def _facade_modules(directory: Path, *, methods: bool) -> dict[str, tuple[str, ...]]:
    result: dict[str, tuple[str, ...]] = {}
    for path in sorted(directory.glob("*.py")):
        if path.name == "__init__.py":
            continue
        try:
            content = path.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as error:
            raise GenerationError(f"cannot inspect facade module {path}") from error
        if content.startswith(GENERATED_HEADER):
            continue
        names = _defined_methods(path) if methods else _defined_public_types(path)
        if names:
            result[path.stem] = names
    return result


def _manifest_path(output: Path) -> Path:
    if output.resolve() == (REPOSITORY_ROOT / "pypokerlost").resolve():
        return MANIFEST_ROOT / "flat.json"
    return output.parent / ".pypokerlost-generated" / "flat.json"


def _manifest_content(
    documents: Sequence[SourceDocument],
    owned_files: Iterable[Path],
) -> str:
    value = {
        "manifest_version": 3,
        "generator_version": GENERATOR_VERSION,
        "sources": [
            {
                "title": document.title,
                "openapi_version": document.version,
                "source_sha256": document.source_sha256,
            }
            for document in sorted(
                documents,
                key=lambda item: (item.title, item.source_sha256),
            )
        ],
        "files": sorted(path.as_posix() for path in owned_files),
    }
    return json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


def _previous_owned_files(path: Path) -> tuple[Path, ...]:
    if not path.exists():
        return ()
    try:
        raw = _json_object(path.read_text(encoding="utf-8"), location=str(path))
        files = _sequence(raw.get("files"), location=f"{path}.files")
    except (OSError, UnicodeError) as error:
        raise GenerationError(f"failed to read generation manifest {path}") from error
    result: list[Path] = []
    for value in files:
        rendered = _string(value, location=f"{path}.files[]")
        candidate = Path(rendered)
        if candidate.is_absolute() or ".." in candidate.parts or candidate.suffix != ".py":
            raise GenerationError(f"generation manifest contains unsafe path {rendered!r}")
        result.append(candidate)
    return tuple(result)


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=path.parent,
        prefix=f".{path.name}.",
        suffix=".tmp",
        delete=False,
    ) as stream:
        temporary = Path(stream.name)
        stream.write(content)
    temporary.replace(path)


def generate(
    documents: Sequence[SourceDocument],
    *,
    output: Path,
    scope_map: Mapping[PokerlostOperation, tuple[PokerlostScope, ...]],
    check: bool,
) -> str:
    """Preflight globally, then check or write the complete generator-owned state."""
    operations = collect_operations(documents)
    known_operations = frozenset(operation.operation for operation in operations)
    unknown_scope_operations = sorted(set(scope_map) - known_operations)
    if unknown_scope_operations:
        names = ", ".join(str(operation) for operation in unknown_scope_operations)
        raise GenerationError(f"scope map contains unknown operations: {names}")
    types = collect_types(operations)
    output = output.resolve()
    methods_directory = output / "methods"
    types_directory = output / "types"
    rendered: list[RenderedFile] = []
    generated_method_names: dict[str, tuple[str, ...]] = {}
    generated_type_names: dict[str, tuple[str, ...]] = {}

    for type_spec in types:
        relative = Path("types") / f"{type_spec.module_name}.py"
        target = output / relative
        if target.exists() and not target.read_text(encoding="utf-8").startswith(GENERATED_HEADER):
            raise GenerationError(
                f"hand-written type {target} collides with generator-owned OpenAPI schema "
                f"{type_spec.name}"
            )
        rendered.append(RenderedFile(relative, render_type(type_spec)))
        generated_type_names[type_spec.module_name] = (type_spec.name,)

    for operation in operations:
        relative = Path("methods") / f"{operation.module_name}.py"
        target = output / relative
        scopes = scope_map.get(operation.operation)
        if target.exists() and not target.read_text(encoding="utf-8").startswith(GENERATED_HEADER):
            declared_operation, declared_scopes, declared_fields, declared_returning = (
                _method_metadata(target, operation.class_name)
            )
            if declared_operation != operation.operation:
                raise GenerationError(f"{target} operation metadata does not match OpenAPI")
            payload_fields, _ = _required_fields(
                operation.payload_schema,
                operation.source,
                location=f"{operation.operation}.payload",
            )
            if declared_fields != frozenset(payload_fields):
                raise GenerationError(f"{target} payload fields do not match OpenAPI")
            result_reference = _direct_reference(operation.result_schema)
            if result_reference is not None and declared_returning != result_reference:
                raise GenerationError(f"{target} result metadata does not match OpenAPI")
            if operation.result_schema.get("type") == "null" and declared_returning != "None":
                raise GenerationError(f"{target} null result metadata does not match OpenAPI")
            scopes = declared_scopes
            if operation.protected != bool(scopes):
                raise GenerationError(f"{target} authorization metadata does not match body schema")
            mapped_scopes = scope_map.get(operation.operation)
            if mapped_scopes is not None and mapped_scopes != scopes:
                raise GenerationError(f"{target} scopes do not match explicit scope map")
            continue
        if operation.protected and not scopes:
            raise GenerationError(
                f"protected operation {operation.operation} needs a hand-written method "
                "or non-empty explicit scope-map entry"
            )
        scopes = scopes or ()
        if not operation.protected and scopes:
            raise GenerationError(f"public operation {operation.operation} cannot declare scopes")
        rendered.append(RenderedFile(relative, render_method(operation, scopes)))
        generated_method_names[operation.module_name] = (operation.class_name,)

    method_modules = _facade_modules(methods_directory, methods=True)
    method_modules.update(generated_method_names)
    type_modules = _facade_modules(types_directory, methods=False)
    type_modules.update(generated_type_names)
    rendered.extend(
        (
            RenderedFile(
                Path("methods/__init__.py"),
                _render_facade(
                    title="Flat public Pokerlost method facade",
                    modules=method_modules,
                ),
            ),
            RenderedFile(
                Path("types/__init__.py"),
                _render_facade(
                    title="Flat public Pokerlost type facade",
                    modules=type_modules,
                ),
            ),
        )
    )
    rendered.sort(key=lambda item: item.path.as_posix())
    manifest_path = _manifest_path(output)
    owned_files = tuple(item.path for item in rendered)
    expected_manifest = _manifest_content(documents, owned_files)
    previous_files = _previous_owned_files(manifest_path)
    current_files = frozenset(owned_files)
    differences: list[str] = []
    for item in rendered:
        target = output / item.path
        try:
            current = target.read_text(encoding="utf-8")
        except FileNotFoundError:
            current = None
        except (OSError, UnicodeError) as error:
            raise GenerationError(f"failed to read generated target {target}") from error
        if current != item.content:
            differences.append(item.path.as_posix())
    stale = tuple(path for path in previous_files if path not in current_files)
    differences.extend(f"stale:{path.as_posix()}" for path in stale)
    try:
        current_manifest = manifest_path.read_text(encoding="utf-8")
    except FileNotFoundError:
        current_manifest = None
    except (OSError, UnicodeError) as error:
        raise GenerationError(f"failed to read generation manifest {manifest_path}") from error
    if current_manifest != expected_manifest:
        differences.append("manifest")
    if check:
        if differences:
            raise GenerationError(
                "generated SDK sources are out of date: " + ", ".join(differences)
            )
        return f"{len(operations)} operations and {len(types)} types are up to date"

    for item in rendered:
        target = output / item.path
        if target.exists() and item.path.name != "__init__.py":
            current = target.read_text(encoding="utf-8")
            if not current.startswith(GENERATED_HEADER):
                raise GenerationError(f"refusing to overwrite non-generator file {target}")
    for relative in stale:
        target = output / relative
        if relative.name == "__init__.py" or not target.exists():
            continue
        current = target.read_text(encoding="utf-8")
        if not current.startswith(GENERATED_HEADER):
            raise GenerationError(f"refusing to remove non-generator file {target}")

    for item in rendered:
        target = output / item.path
        _atomic_write(target, item.content)
    for relative in stale:
        target = output / relative
        if relative.name == "__init__.py" or not target.exists():
            continue
        target.unlink()
    _atomic_write(manifest_path, expected_manifest)
    return f"generated {len(operations)} operations and {len(types)} flat types"


def _read_source(path: Path) -> SourceDocument:
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as error:
        raise GenerationError(f"failed to read OpenAPI file {path}") from error
    return parse_document(_json_object(text, location=str(path)), label=str(path))


async def _fetch_source(base_url: str, timeout: float) -> SourceDocument:
    if type(timeout) is bool or not isinstance(timeout, int | float) or timeout <= 0:
        raise GenerationError("service timeout must be positive")
    try:
        server = PokerlostAPIServer(base_url)
    except (TypeError, ValueError) as error:
        raise GenerationError(
            "service URL must be a root HTTPS URL or loopback HTTP URL"
        ) from error
    try:
        async with httpx.AsyncClient(timeout=float(timeout), trust_env=False) as client:
            response = await client.get(server.operation_url(PokerlostOperation("getOpenApi")))
            decoded: object = response.json()
    except (httpx.HTTPError, ValueError) as error:
        raise GenerationError("OpenAPI publication request failed") from error
    envelope = _mapping(decoded, location="OpenAPI publication response")
    if envelope.get("ok") is not True:
        raise GenerationError("service refused OpenAPI publication")
    result = _mapping(envelope.get("result"), location="OpenAPI publication result")
    return parse_document(result, label=base_url)


